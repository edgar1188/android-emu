#[tauri::command]
pub fn sync_theme(window: tauri::Window, is_dark: bool) {
    #[cfg(target_os = "linux")]
    {
        use gtk::prelude::*;
        let _ = window.clone().run_on_main_thread(move || {
            if let Ok(gtk_window) = window.gtk_window() {
                if let Some(titlebar) = gtk_window.titlebar() {
                    let header_bar =
                        if let Some(event_box) = titlebar.downcast_ref::<gtk::EventBox>() {
                            event_box
                                .children()
                                .get(0)
                                .cloned()
                                .and_then(|c| c.downcast::<gtk::HeaderBar>().ok())
                        } else {
                            titlebar.clone().downcast::<gtk::HeaderBar>().ok()
                        };

                    if let Some(hb) = header_bar {
                        let context = hb.style_context();
                        if is_dark {
                            context.add_class("is-dark");
                        } else {
                            context.remove_class("is-dark");
                        }

                        // Update logo
                        for child in hb.children() {
                            if child.widget_name() == "canaima-logo" {
                                if let Ok(image) = child.downcast::<gtk::Image>() {
                                    let svg_data = if is_dark {
                                        CANAIMA_LOGO_SVG
                                            .replace("#1a1a1a", "#ffffff")
                                            .replace("fill:#1a1a1a", "fill:#ffffff")
                                    } else {
                                        CANAIMA_LOGO_SVG.to_string()
                                    };
                                    if let Ok(loader) =
                                        gtk::gdk_pixbuf::PixbufLoader::with_type("svg")
                                    {
                                        let _ = loader.write(svg_data.as_bytes());
                                        let _ = loader.close();
                                        if let Some(pixbuf) = loader.pixbuf() {
                                            if let Some(scaled) = pixbuf.scale_simple(
                                                118,
                                                20,
                                                gtk::gdk_pixbuf::InterpType::Bilinear,
                                            ) {
                                                image.set_from_pixbuf(Some(&scaled));
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        });
    }
}


            header_bar.style_context().add_class("custom-headerbar");
            header_bar.set_widget_name("canaima-headerbar");

            // Set Title (Center)
            let title_str = gtk_window
                .title()
                .map(|s| s.to_string())
                .unwrap_or_else(|| "Canaima App".to_string());
